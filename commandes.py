"""Bons d'enlevement : enregistrement par le client, liste et statut dans l'administration."""
import json
from decimal import Decimal, InvalidOperation
from pathlib import Path

from flask import jsonify, request, send_from_directory, session, abort

import acces_utilisateurs

STATUTS = ('attente', 'recuperee')
DUREES = ('cash', '6', '12', '18', '24')
FICHIERS_ADMIN = {
    'admin-commandes.html': 'text/html; charset=utf-8',
    'admin-commandes.js': 'application/javascript; charset=utf-8',
    'admin-commandes.css': 'text/css; charset=utf-8',
    'admin-tableau-bord.js': 'application/javascript; charset=utf-8',
    'admin-tableau-bord.css': 'text/css; charset=utf-8',
}


def texte(valeur, longueur, nom):
    valeur = str(valeur or '').strip()
    if not valeur or len(valeur) > longueur:
        raise ValueError(f'{nom} : champ requis (maximum {longueur} caractères).')
    return valeur


def nombre(valeur, nom, maximum=Decimal('999999999')):
    try:
        montant = Decimal(str(valeur or '0'))
    except InvalidOperation as exc:
        raise ValueError(f'{nom} : montant invalide.') from exc
    if not montant.is_finite() or montant < 0 or montant > maximum:
        raise ValueError(f'{nom} : montant hors limites.')
    return montant


def installer(app, srv):
    def connexion():
        return srv['ouvrir_connexion'](srv['NOM_BASE'])

    def preparer_table(cn):
        cn.execute('''CREATE TABLE IF NOT EXISTS public.commandes_bon (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        cree_le timestamptz NOT NULL DEFAULT now(),
                        utilisateur_id bigint REFERENCES public.utilisateurs_catalogue(id) ON DELETE SET NULL,
                        nom text NOT NULL,
                        entreprise text NOT NULL,
                        ville text NOT NULL,
                        telephone text NOT NULL,
                        boutique text NOT NULL,
                        duree text NOT NULL,
                        lignes jsonb NOT NULL,
                        montant_comptant numeric NOT NULL,
                        mensualite numeric NOT NULL DEFAULT 0,
                        statut text NOT NULL DEFAULT 'attente' CHECK (statut IN ('attente', 'recuperee')))''')

    @app.post('/commande')
    def enregistrer_commande():
        uid = session.get('utilisateur_id')
        if not uid:
            return jsonify(erreur='Connexion requise.'), 401
        donnees = request.get_json(silent=True) or {}
        try:
            nom = texte(donnees.get('nom'), 120, 'Nom')
            entreprise = texte(donnees.get('entreprise'), 160, "Nom de l'entreprise")
            ville = texte(donnees.get('ville'), 80, 'Ville')
            telephone = texte(donnees.get('telephone'), 30, 'Téléphone')
            boutique = texte(donnees.get('boutique'), 120, 'BrandShop')
            duree = str(donnees.get('duree') or '')
            if duree not in DUREES:
                raise ValueError('Durée de paiement invalide.')
            mensualite = nombre(donnees.get('mensualite'), 'Mensualité')
            lignes_envoyees = donnees.get('lignes')
            if not isinstance(lignes_envoyees, list) or not 1 <= len(lignes_envoyees) <= 50:
                raise ValueError('Sélection vide ou trop longue.')
            # Les prix sont recalculés côté serveur, à partir des offres de cette session.
            offres = {p['reference']: p for p in acces_utilisateurs.appliquer_offre(srv, srv['charger_catalogue'](), uid)['products']}
            lignes, comptant = [], Decimal('0')
            for ligne in lignes_envoyees:
                reference = texte(ligne.get('reference'), 60, 'Référence')
                quantite = int(ligne.get('qty') or 0)
                if reference not in offres or not 1 <= quantite <= 99:
                    raise ValueError(f'Produit non disponible pour cette session : {reference}.')
                prix = Decimal(str(offres[reference]['offerPrice']))
                comptant += prix * quantite
                lignes.append({'reference': reference, 'nom': offres[reference]['name'], 'qty': quantite, 'prix': float(prix)})
        except (ValueError, TypeError) as exc:
            return jsonify(erreur=str(exc)), 400
        with connexion() as cn:
            preparer_table(cn)
            row = cn.execute(
                '''INSERT INTO public.commandes_bon (utilisateur_id, nom, entreprise, ville, telephone, boutique, duree, lignes, montant_comptant, mensualite)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s::jsonb,%s,%s) RETURNING id''',
                (uid, nom, entreprise, ville, telephone, boutique, duree, json.dumps(lignes, ensure_ascii=False), comptant, mensualite)).fetchone()
        return jsonify(ok=True, id=row['id'], montant_comptant=float(comptant)), 201

    @app.get('/admin/api/commandes')
    def lister_commandes():
        with connexion() as cn:
            preparer_table(cn)
            lignes = cn.execute('''SELECT c.id, c.cree_le, c.nom, c.entreprise, c.ville, c.telephone, c.boutique, c.duree,
                                          c.lignes, c.montant_comptant, c.mensualite, c.statut, u.identifiant AS session
                                   FROM public.commandes_bon c LEFT JOIN public.utilisateurs_catalogue u ON u.id = c.utilisateur_id
                                   ORDER BY c.cree_le DESC LIMIT 2000''').fetchall()
        return jsonify(commandes=[{
            'id': r['id'], 'date': r['cree_le'].strftime('%d/%m/%Y %H:%M'), 'iso': r['cree_le'].isoformat(), 'nom': r['nom'], 'entreprise': r['entreprise'],
            'ville': r['ville'], 'telephone': r['telephone'], 'boutique': r['boutique'], 'duree': r['duree'],
            'lignes': r['lignes'], 'montant': float(r['montant_comptant']), 'mensualite': float(r['mensualite']),
            'statut': r['statut'], 'session': r['session'] or '',
        } for r in lignes])

    @app.post('/admin/api/commandes/<int:cid>/statut')
    def changer_statut_commande(cid):
        statut = str((request.get_json(silent=True) or {}).get('statut') or '')
        if statut not in STATUTS:
            return jsonify(erreur='Statut invalide.'), 400
        with connexion() as cn:
            preparer_table(cn)
            cible = cn.execute('UPDATE public.commandes_bon SET statut = %s WHERE id = %s RETURNING id', (statut, cid)).fetchone()
        if not cible:
            return jsonify(erreur='Commande introuvable.'), 404
        return jsonify(ok=True)

    @app.get('/admin/commandes')
    def page_commandes():
        return send_from_directory(srv['DOSSIER'], 'admin-commandes.html')

    @app.get('/admin/commandes/<nom>')
    def fichier_commandes(nom):
        if nom not in FICHIERS_ADMIN:
            abort(404)
        return send_from_directory(srv['DOSSIER'], nom, mimetype=FICHIERS_ADMIN[nom].split(';')[0])
